/* global __dirname */
// Draws the board's pieces - the chessboard library's default set - as SVG,
// into src/lib/chessboard/defaultPieceSet.ts:
//   node scripts/generate-pieces.js
// Our own drawings, flat and geometric: each piece a few shapes in a 100x100
// box, filled with its side's color and outlined, with lines on top for its
// features (a bishop's slit, a knight's eye and mane). White's outline keeps
// it clear of a light square; on black, faint light seams between a piece's
// parts keep it from reading as one blob on a dark one. Another set is
// another table of shapes and colors.
const fs = require('fs');
const path = require('path');

const OUT = path.join(
  __dirname,
  '..',
  'src',
  'lib',
  'chessboard',
  'defaultPieceSet.ts',
);

const STROKE_WIDTH = 2.6;

const COLORS = {
  w: { fill: '#f8f7f3', stroke: '#1f1f1f', detail: '#1f1f1f' },
  b: { fill: '#2c2c2e', stroke: '#111111', detail: '#e9e9e9' },
};

// A piece's layers, bottom first:
// - shape: filled with the side's color, outlined
// - line: a feature drawn over it, dark on white and light on black
// - dot: a feature filled in, the same way
// - seam: where two parts meet - drawn on black only, where the outlines
//   don't show it
const shape = (el) => ['shape', el];
const line = (el) => ['line', el];
const dot = (el) => ['dot', el];
const seam = (el) => ['seam', el];

const base = (x0 = 22, x1 = 78) =>
  shape(`<rect x="${x0}" y="79" width="${x1 - x0}" height="9" rx="3"/>`);
const collar = (x0, x1, y0, y1) =>
  shape(
    `<rect x="${x0}" y="${y0}" width="${x1 - x0}" height="${y1 - y0}" rx="2"/>`,
  );

