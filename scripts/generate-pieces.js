function pieceSvg(color, type) {
  const c = COLORS[color];
  const layers = PIECES[type].map(([kind, el]) => {
    switch (kind) {
      case 'shape':
        return `<g fill="${c.fill}" stroke="${c.stroke}">${el}</g>`;
      case 'line':
        return `<g fill="none" stroke="${c.detail}">${el}</g>`;
      case 'dot':
        return `<g fill="${c.detail}" stroke="none">${el}</g>`;
      case 'seam':
        return color === 'b'
          ? `<g fill="none" stroke="${c.detail}" stroke-width="1.6" opacity="0.55">${el}</g>`
          : '';
      default:
        throw new Error(`unknown layer ${kind}`);
    }
  });
  return (
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">' +
    `<g stroke-width="${STROKE_WIDTH}" stroke-linejoin="round" stroke-linecap="round">` +
    `${layers.join('')}</g></svg>`
  );
}

const entries = ['w', 'b'].flatMap((color) =>
  Object.keys(PIECES).map(
    (type) => `  ${color}${type}: '${pieceSvg(color, type)}',`,
  ),
);

fs.writeFileSync(
  OUT,
  `// Generated by scripts/generate-pieces.js - change the drawings there and run
// it again, rather than editing this file.
import { PieceSet } from './types';

// The board's own pieces, drawn for it: used unless it's given another set.
export const defaultPieceSet: PieceSet = {
${entries.join('\n')}
};
`,
);
